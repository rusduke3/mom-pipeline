# Пути к бинарникам ffmpeg/ffprobe с фолбэком на imageio-ffmpeg (работает «из коробки» без системного ffmpeg).
def _resolve_ffmpeg_bin() -> Path:
    explicit = os.getenv("FFMPEG_BIN")
    if explicit:
        return Path(explicit)
    found = shutil.which("ffmpeg")
    if found:
        return Path(found)
    if imageio_ffmpeg is not None:
        return Path(imageio_ffmpeg.get_ffmpeg_exe())
    # Никакого ffmpeg в системе — путь упадёт при вызове, но не при импорте модуля
    return Path("ffmpeg")


def _resolve_ffprobe_bin(ffmpeg_bin: Path) -> Path:
    explicit = os.getenv("FFPROBE_BIN")
    if explicit:
        return Path(explicit)
    # ffprobe рядом с ffmpeg (сохраняем суффикс .exe на Windows)
    candidate = ffmpeg_bin.with_name("ffprobe" + ffmpeg_bin.suffix)
    if candidate.exists():
        return candidate
    found = shutil.which("ffprobe")
    if found:
        return Path(found)
    # Если ffprobe вообще отсутствует — get_video_duration откатится на фолбэк первых 60 секунд
    return candidate


FFMPEG_BIN = _resolve_ffmpeg_bin()
FFPROBE_BIN = _resolve_ffprobe_bin(FFMPEG_BIN)

